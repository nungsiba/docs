// ============================================================
// DOCSAVER — PDF generation
// Two paths:
//  1) imageFileToPdfBlob   — wraps an uploaded photo/scan into a PDF
//  2) fieldsToPdfBlob      — renders a typed-in form into a formatted PDF
// Both run entirely in the browser (jsPDF), no server needed.
// ============================================================

async function fileToDataUrl(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = reject;
    reader.readAsDataURL(file);
  });
}

// Re-encodes ANY browser-loadable image (JPEG, PNG, WEBP, camera
// HEIC-as-decoded-by-the-browser, etc.) into a plain JPEG data URL
// via canvas. This guarantees jsPDF always receives a format it
// actually understands, instead of guessing from the file's
// reported MIME type (which was silently producing broken PDFs for
// anything that wasn't already a plain .jpg or .png).
async function normalizeImageToJpegDataUrl(source) {
  const dataUrl = typeof source === "string" ? source : await fileToDataUrl(source);
  const img = new Image();
  await new Promise((resolve, reject) => {
    img.onload = resolve;
    img.onerror = () => reject(new Error("That file couldn't be read as an image."));
    img.src = dataUrl;
  });

  const canvas = document.createElement("canvas");
  canvas.width = img.naturalWidth || img.width;
  canvas.height = img.naturalHeight || img.height;
  const ctx = canvas.getContext("2d");
  // White backing so transparent PNGs don't turn black when
  // flattened to JPEG.
  ctx.fillStyle = "#ffffff";
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.drawImage(img, 0, 0);

  return {
    dataUrl: canvas.toDataURL("image/jpeg", 0.92),
    width: canvas.width,
    height: canvas.height
  };
}

// ---- 1. Image upload -> PDF -------------------------------

async function imageFileToPdfBlob(file) {
  const { dataUrl, width, height } = await normalizeImageToJpegDataUrl(file);

  const { jsPDF } = window.jspdf;
  // Fit page to the image's aspect ratio, A4-max
  const maxW = 595, maxH = 842; // A4 in pt
  const scale = Math.min(maxW / width, maxH / height, 1);
  const w = width * scale, h = height * scale;

  const doc = new jsPDF({
    orientation: w > h ? "landscape" : "portrait",
    unit: "pt",
    format: [w, h]
  });
  doc.addImage(dataUrl, "JPEG", 0, 0, w, h);
  return doc.output("blob");
}

// ---- 2. Typed fields -> formatted PDF ----------------------

async function fieldsToPdfBlob(docTypeKey, values) {
  const type = DOC_TYPES[docTypeKey];
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF({ unit: "pt", format: "a4" });

  const marginX = 56;
  let y = 70;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("DOCSAVER", marginX, y);
  doc.setFontSize(11);
  doc.setTextColor(110, 110, 110);
  doc.text("Family document record", marginX, y + 16);
  doc.setTextColor(20, 20, 20);

  y += 40;
  doc.setDrawColor(200, 200, 200);
  doc.line(marginX, y, 595 - marginX, y);
  y += 28;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.text(type.label, marginX, y);
  y += 30;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);

  // photo/signature (if provided as data URLs in values.__images)
  const images = values.__images || {};

  for (const field of type.fields) {
    if (field.kind === "photo" || field.kind === "signature") {
      const dataUrl = images[field.key];
      doc.setFont("helvetica", "bold");
      doc.text(field.label + ":", marginX, y);
      y += 6;
      if (dataUrl) {
        const imgH = field.kind === "photo" ? 90 : 40;
        const normalized = await normalizeImageToJpegDataUrl(dataUrl);
        const imgW = imgH * (normalized.width / normalized.height);
        doc.addImage(normalized.dataUrl, "JPEG", marginX, y, imgW, imgH);
        y += imgH + 16;
      } else {
        doc.setFont("helvetica", "italic");
        doc.setTextColor(150, 150, 150);
        doc.text("(not provided)", marginX, y + 12);
        doc.setTextColor(20, 20, 20);
        y += 28;
      }
      continue;
    }

    const val = values[field.key] || "—";
    doc.setFont("helvetica", "bold");
    doc.text(field.label + ":", marginX, y);
    doc.setFont("helvetica", "normal");
    doc.text(String(val), marginX + 230, y);
    y += 24;

    if (y > 770) {
      doc.addPage();
      y = 60;
    }
  }

  y += 20;
  doc.setDrawColor(220, 220, 220);
  doc.line(marginX, y, 595 - marginX, y);
  y += 16;
  doc.setFontSize(9);
  doc.setTextColor(140, 140, 140);
  doc.text(
    `Generated by DOCSAVER on ${new Date().toLocaleDateString()}`,
    marginX,
    y
  );

  return doc.output("blob");
}
